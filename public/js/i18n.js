window.t = function t(key, vars) {
  const lang = window.currentLang || 'en';
  const dict = window.I18N[lang] || window.I18N.en;
  let s = dict[key] ?? window.I18N.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
};
